"""Generate paper table rows from the audited operator cohort; never run TVM."""

import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "papers/figures/operator800_20261011_cohort/summary.json"
OUT = ROOT / "papers/tables/operator800_completed"
NAMES = {
    "matmul128": "MatMul128",
    "matmul256": "MatMul256",
    "conv2d_nchw3x3": "Conv2D",
    "reduction4096": "Reduction",
}


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fmt(value, digits=2):
    return "NR" if value is None else f"{value:.{digits}f}"


def target(run, latency):
    return next((p["tune_s"] / 60 for p in run["curve"] if p["best_us"] <= latency), None)


def rows_file(name, rows):
    text = "% Generated by experiments/build_operator800_paper_tables.py.\n"
    headers = {
        "endpoints.tex": "算子 & B & C & D & 提交数 B/C/D",
        "retiming.tex": "算子 / 配置 & 中位数 & [P25, P75] & 相对 B 的性能",
        "convergence.tex": r"算子 / 配置 & \shortstack{自身最佳\\提交数} & \shortstack{自身最佳\\时间} & \shortstack{严格\\目标} & \shortstack{+1\%\\目标} & \shortstack{+5\%\\目标} & 总调优",
        "candidates.tex": r" & \multicolumn{3}{c}{B：MetaSchedule} & \multicolumn{3}{c}{C：CS+H} \\" + "\n" + "算子 & 生成数 & Verify 失败 & 通过率 & 生成数 & Verify 失败 & 通过率",
        "model_cost.tex": r"算子 / 配置 & \shortstack{累计\\样本} & \shortstack{更新回调\\次数} & \shortstack{模型评分\\输入数} & \shortstack{模型评分\\时间} & \shortstack{模型更新\\时间} & \shortstack{Draft\\时间}",
        "phases.tex": "算子 / 配置 & 搜索 & 编译 & 测量与反馈 & 回调 & 其他 & 总调优",
    }
    if name == "endpoints.tex":
        text += r"\begin{tabular}{@{}lrrrr@{}}" + "\n"
    else:
        width = r"0.92\textwidth" if name == "retiming.tex" else r"\textwidth"
        columns = "lrrr" if name == "retiming.tex" else "lrrrrrr"
        text += rf"\begin{{tabular*}}{{{width}}}{{@{{\extracolsep{{\fill}}}}{columns}@{{}}}}" + "\n"
    text += "\\toprule\n" + headers[name] + " \\\\\n\\midrule\n"
    text += "\n".join(" & ".join(map(str, row)) + r" \\" if row else r"\midrule" for row in rows)
    ending = "tabular" if name == "endpoints.tex" else "tabular*"
    text += "\n\\bottomrule\n" + rf"\end{{{ending}}}" + "\n"
    (OUT / name).write_text(text, encoding="utf-8")


def main():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    assert data["completion_ready"] and not data["pending"]
    runs = {(r["workload"], r["arm"]): r for r in data["runs"]}
    assert len(runs) == 12
    retiming = {(g["workload"], r["name"]): r for g in data["retiming"] for r in g["arms"]}
    pytorch = {r["workload"]: r for r in data["pytorch"]}
    assert len(retiming) == 12 and len(pytorch) == 4
    OUT.mkdir(parents=True, exist_ok=True)
    endpoint_rows, retiming_rows, convergence_rows = [], [], []
    candidate_rows, model_rows, phase_rows, metrics = [], [], [], []
    input_hashes = {str(SOURCE.relative_to(ROOT)): digest(SOURCE)}
    for workload, label in NAMES.items():
        base = runs[workload, "B"]
        group = [runs[workload, arm] for arm in "BCD"]
        endpoint_rows.append([label, *[fmt(r["best_us"], 3) for r in group],
                              "/".join(str(r["budget"]["actual_submitted"]) for r in group)])
        candidate_row = [label]
        for run in group[:2]:
            accounting = run["search_totals"]["accounting"]
            assert accounting["conservation_ok"]
            candidate_row += [run["generated"], run["verify_failed"],
                              f"{100 * accounting['passed'] / run['generated']:.1f}\\%"]
        if workload == "conv2d_nchw3x3":
            candidate_row[0] += r"$^{\dagger}$"
        candidate_rows.append(candidate_row)
        for arm in "BCD":
            run, retime = runs[workload, arm], retiming[workload, arm]
            path = Path(run["result_path"])
            assert digest(path) == run["result_sha256"] == retime["result_sha256"]
            assert len(retime["samples_us"]) == 30
            assert all(c["passed"] for c in retime["checks"])
            assert run["outcomes"]["finite"] == run["budget"]["actual_submitted"]
            assert run["xgb_data_size"] == run["budget"]["actual_submitted"]
            # The outer Tune stopwatch also includes sub-millisecond boundary overhead.
            assert abs(sum(run["phases_s"].values()) - run["tune_s"]) < 0.01
            input_hashes[str(path.relative_to(ROOT))] = run["result_sha256"]
            title = f"{label} / {arm}"
            dagger = workload == "conv2d_nchw3x3" and arm == "C"
            marked = title + (r"$^{\dagger}$" if dagger else "")
            retiming_rows.append([title, fmt(retime["median_us"], 3),
                                 f"[{retime['p25_us']:.3f}, {retime['p75_us']:.3f}]",
                                 fmt(retiming[workload, "B"]["median_us"] / retime["median_us"], 3)])
            targets = {str(ratio): target(run, ratio * base["best_us"]) for ratio in (1.0, 1.01, 1.05)}
            own = run["own_best"]
            convergence_rows.append([title, own["submitted"], fmt(own["tune_s"] / 60),
                                     *[fmt(t) for t in targets.values()], fmt(run["tune_s"] / 60)])
            updates = run["model_progress"]
            model_update_s = sum(p["update_s"] for p in updates)
            model_rows.append([marked, run["xgb_data_size"], len(updates), run["xgb_inputs"],
                               fmt(run["xgb_prediction_s"], 3), fmt(model_update_s, 3),
                               fmt(run["draft_scoring_s"], 3) if arm == "D" else "--"])
            phases = {k: run["phases_s"][k] / 60 for k in (
                "search_s", "builder_s", "runner_and_notify_s", "callbacks_s", "residual_s")}
            phase_rows.append([title, *[fmt(v) for v in phases.values()], fmt(run["tune_s"] / 60)])
            metrics.append({"workload": workload, "arm": arm, "best_us": run["best_us"],
                            "submitted": run["budget"]["actual_submitted"], "target_min": targets,
                            "tune_min": run["tune_s"] / 60, "phases_min": phases,
                            "model_update_s": model_update_s, "internal_counters_include_restore": dagger})
        ref = pytorch[workload]
        assert ref["status"] == "completed" and len(ref["samples_us"]) == 30
        assert all(c["passed"] for c in ref["checks"])
        retiming_rows.append([f"{label} / PyTorch", fmt(ref["median_us"], 3),
                             f"[{ref['p25_us']:.3f}, {ref['p75_us']:.3f}]", "--"])
        if workload != "reduction4096":
            for rows in (retiming_rows, convergence_rows, model_rows, phase_rows):
                rows.append([])
    assert sum(r["budget"]["actual_submitted"] for r in runs.values()) == 7461
    for name, rows in [("endpoints.tex", endpoint_rows), ("retiming.tex", retiming_rows),
                       ("convergence.tex", convergence_rows), ("candidates.tex", candidate_rows),
                       ("model_cost.tex", model_rows), ("phases.tex", phase_rows)]:
        rows_file(name, rows)
    (OUT / "metrics.json").write_text(json.dumps(metrics, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    manifest = {"source": str(SOURCE.relative_to(ROOT)), "seed": data["seed"],
                "inputs_sha256": input_hashes, "script_sha256": digest(Path(__file__)),
                "outputs_sha256": {p.name: digest(p) for p in sorted(OUT.iterdir()) if p.name != "manifest.json"}}
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Generated six tables from 12 audited runs / 7461 submissions: {OUT}")


if __name__ == "__main__":
    main()
